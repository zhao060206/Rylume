"""Build the offline desktop stylesheet with explicit, stable cascade layers.

No CDN or node runtime is required by the installed application. Feature styles
are kept in a low-priority layer; all chrome uses the shared component system.
"""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]
FEATURES = [
    'studio.css', 'annotation.css', 'relation-definition.css', 'delivery.css',
    'styles/feature-panels.css', 'generation-workflow.css',
    'creation-composer.css', 'onboarding.css',
    'document-assistant.css', 'floating-windows.css',
    'save-ui.css', 'figure-import.css', 'vector-details.css', 'element-editor.css',
]
SYSTEM = ['styles/components.css', 'styles/workspace.css', 'styles/panels.css']

def build():
    ui = ROOT / 'ui'
    legacy = '\n'.join(f'/* {name} */\n' + (ui / name).read_text('utf-8') for name in FEATURES)
    system = '\n'.join((ui / name).read_text('utf-8') for name in SYSTEM)
    return ('/* Generated by scripts/build_ui.py. Edit ui/styles/*.css. */\n'
            '@layer features, components, workspace, panels;\n'
            '@layer features {\n' + legacy + '\n}\n' + system)

if __name__ == '__main__':
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); args = parser.parse_args()
    path = ROOT / 'ui/workbench-ui.css'; content = build()
    if args.check:
        if not path.exists() or path.read_text('utf-8') != content:
            raise SystemExit('UI styles are stale. Run python scripts/build_ui.py')
        print('UI stylesheet matches its source components.')
    else:
        path.write_text(content, 'utf-8')
        print(f'Built {path.name}: {len(content.encode()):,} bytes; one offline stylesheet.')
